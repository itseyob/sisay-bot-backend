function isValidTable(table) {
  const t = parseInt(table);
  return t >= 1 && t <= 20;
}

function checkRateLimit(table) {
  const now = Date.now();
  const last = rateLimit[table] || 0;
  if (now - last < 20000) return false;
  rateLimit[table] = now;
  return true;
}

